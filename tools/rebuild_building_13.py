#!/usr/bin/env python3
"""
tools/rebuild_building_13.py

Restores the house structure exactly as originally modeled before any manual wall changes:
- 'Building_Base': The intact, single-piece house mesh as originally generated by the UO3D engine:
  * All 3 vertical floors/tiers preserved.
  * Windows with sill, lintel, and side frames intact (no gaps/espações).
  * Walls, gables, floors, stairs as originally modeled.
- 'Telhado' (Roof):
  * Completely separated from the house.
  * Each roof tile/square is an independent LEGO block object ("cada quadrado é um bloco").
  * Smooth underside (no staircase / degraus).

Exports:
- map0_felucca/britain/building_13_royal_guard_outpost/building_lego.blend:
  * Collection "01_Casa_Base": 'Building_Base' (single solid house object as originally modeled)
  * Collection "02_Telhado_Lego": 273 individual roof tile blocks ("cada quadrado é um bloco")
- map0_felucca/britain/building_13_royal_guard_outpost/model_base.glb:
  * Multi-mesh GLB with 'Building_Base' and 'Building_Roof' separated.
- map0_felucca/britain/building_13_royal_guard_outpost/model_modular_lego.glb:
  * Multi-node GLB with 'Building_Base' + 273 individual roof tile objects.
- map0_felucca/britain/building_13_royal_guard_outpost/model_base_house.glb
- map0_felucca/britain/building_13_royal_guard_outpost/model_base_roof.glb
- Synchronized to /home/mnunes/uo3d_map/community_assets/map0_felucca/britain/building_13_royal_guard_outpost/
"""

import os
import sys
import json
import shutil
from pathlib import Path

sys.path.append("/home/mnunes/uo3d_map")
import update_all_community_assets as updater
updater.init_worker()

import bpy

def rebuild(building_rel_path="map0_felucca/britain/building_13_royal_guard_outpost"):
    bpath = Path(building_rel_path).resolve()
    info_path = bpath / "info.json"
    with open(info_path, "r", encoding="utf-8") as f:
        meta = json.load(f)

    b = meta["world_bounds"]
    min_wx, max_wx = b["min_x"], b["max_x"]
    min_wy, max_wy = b["min_y"], b["max_y"]
    base_z = b["base_z"]
    center_x = (min_wx + max_wx + 1) / 2.0
    center_z = (min_wy + max_wy + 1) / 2.0
    y_base_ground = base_z * updater.V_SCALE
    expected_count = meta.get("stats", {}).get("item_count", 0)
    target_ids = {u["id"] for u in meta.get("unique_items", [])}
    items, staidx, statics = updater.collect_building_items(0, min_wx, max_wx, min_wy, max_wy, expected_count, target_ids)

    # Clean Blender scene
    bpy.ops.wm.read_factory_settings(use_empty=True)
    scene = bpy.context.scene
    scene.tool_settings.use_snap = True
    scene.tool_settings.snap_elements = {'INCREMENT'}

    # Collections
    col_house = bpy.data.collections.new("01_Casa_Base")
    col_roof = bpy.data.collections.new("02_Telhado_Lego")
    scene.collection.children.link(col_house)
    scene.collection.children.link(col_roof)

    # Shared materials
    mat_wall = bpy.data.materials.new("Mat_House_Base")
    bsdf_w = mat_wall.node_tree.nodes.get("Principled BSDF")
    if bsdf_w:
        bsdf_w.inputs["Base Color"].default_value = (0.78, 0.65, 0.48, 1.0)
        bsdf_w.inputs["Roughness"].default_value = 0.75

    mat_roof = bpy.data.materials.new("Mat_Thatch_Roof")
    bsdf_r = mat_roof.node_tree.nodes.get("Principled BSDF")
    if bsdf_r:
        bsdf_r.inputs["Base Color"].default_value = (0.82, 0.68, 0.35, 1.0)
        bsdf_r.inputs["Roughness"].default_value = 0.85

    # 1. BUILD HOUSE BASE (EXACT ORIGINAL GENERATOR LOGIC)
    existing_walls = set()
    covered_coords = set()
    for it in items:
        wx, wy, z, item_id, fl, h, name = it
        if (fl & 0x10 != 0) or ("wall" in name) or ("window" in name):
            existing_walls.add((wx, wy))
        if (fl & 0x200 != 0) or ("roof" in name) or ("shingle" in name) or ("floor" in name):
            covered_coords.add((wx, wy))

    roof_corner_y = {}
    pitched_roof_coords = set()
    for it in items:
        wx, wy, z, item_id, fl, h, name = it
        if item_id in updater.TRUE_PITCHED_ROOFS:
            r_yb = (z * updater.V_SCALE) - y_base_ground
            step = 3.0 * updater.V_SCALE
            pitched_roof_coords.add((wx, wy))
            if item_id in updater.ROOF_SLOPE_SOUTH: cnw, cne, csw, cse = r_yb, r_yb, r_yb + step, r_yb + step
            elif item_id in updater.ROOF_SLOPE_NORTH: cnw, cne, csw, cse = r_yb + step, r_yb + step, r_yb, r_yb
            elif item_id in updater.ROOF_SLOPE_EAST: cnw, cne, csw, cse = r_yb, r_yb + step, r_yb, r_yb + step
            elif item_id in updater.ROOF_SLOPE_WEST: cnw, cne, csw, cse = r_yb + step, r_yb + step, r_yb, r_yb
            elif item_id in updater.ROOF_RIDGE_NS or item_id in updater.ROOF_RIDGE_EW: cnw, cne, csw, cse = r_yb, r_yb, r_yb, r_yb
            elif item_id in updater.ROOF_VALLEY_FALL_SE: cnw, cne, csw, cse = r_yb, r_yb, r_yb, r_yb + step
            elif item_id in updater.ROOF_HIP_SOUTH: cnw, cne, csw, cse = r_yb, r_yb, r_yb + step, r_yb + step
            elif item_id in updater.ROOF_HIP_NORTH: cnw, cne, csw, cse = r_yb + step, r_yb + step, r_yb, r_yb
            else: cnw, cne, csw, cse = r_yb, r_yb, r_yb + step, r_yb + step
            roof_corner_y[(wx, wy)] = (cnw, cne, csw, cse)

    # House geometry containers (Blender coordinates: X=wx, Y=wz, Z=yb)
    h_verts = []
    h_faces = []

    def add_house_quad(p0, p1, p2, p3):
        # Convert from UO (x, y_height, z_depth) to Blender (x, z_depth, y_height)
        b0 = (p0[0], p0[2], p0[1])
        b1 = (p1[0], p1[2], p1[1])
        b2 = (p2[0], p2[2], p2[1])
        b3 = (p3[0], p3[2], p3[1])
        base = len(h_verts)
        h_verts.extend([b0, b1, b2, b3])
        h_faces.append((base, base + 2, base + 1))
        h_faces.append((base + 1, base + 2, base + 3))

    def add_house_box(bx0, bx1, by0, by1, bz0, bz1):
        if by1 <= by0 or bx1 <= bx0 or bz1 <= bz0:
            return
        add_house_quad((bx0, by1, bz0), (bx1, by1, bz0), (bx0, by1, bz1), (bx1, by1, bz1))
        add_house_quad((bx0, by0, bz1), (bx1, by0, bz1), (bx0, by0, bz0), (bx1, by0, bz0))
        add_house_quad((bx0, by0, bz0), (bx1, by0, bz0), (bx0, by1, bz0), (bx1, by1, bz0))
        add_house_quad((bx1, by0, bz1), (bx0, by0, bz1), (bx1, by1, bz1), (bx0, by1, bz1))
        add_house_quad((bx0, by0, bz1), (bx0, by0, bz0), (bx0, by1, bz1), (bx0, by1, bz0))
        add_house_quad((bx1, by0, bz0), (bx1, by0, bz1), (bx1, by1, bz0), (bx1, by1, bz1))

    wall_thick = updater.WALL_THICKNESS * updater.H_SCALE

    # Synthetic walls on open facades (from original generator)
    west_pts = sorted([wy for wy in range(min_wy, max_wy + 1) if (min_wx, wy) in existing_walls])
    if len(west_pts) >= 2:
        for idx in range(len(west_pts) - 1):
            y1, y2 = west_pts[idx], west_pts[idx + 1]
            if 1 < y2 - y1 <= 32:
                gap_cov = any((min_wx, y) in covered_coords or (min_wx + 1, y) in covered_coords for y in range(y1 + 1, y2))
                if gap_cov:
                    wx0_w = (min_wx - center_x) * updater.H_SCALE
                    for y in range(y1 + 1, y2):
                        if (min_wx, y) not in existing_walls:
                            wz0 = (y - center_z) * updater.H_SCALE
                            wz1 = wz0 + updater.H_SCALE
                            yt_w = 2.40
                            if (min_wx, y) in pitched_roof_coords:
                                cnw, cne, csw, cse = roof_corner_y[(min_wx, y)]
                                yt_w = min(yt_w, max(cnw, cne, csw, cse))
                            add_house_box(wx0_w, wx0_w + wall_thick, 0.0, yt_w, wz0, wz1)

    east_pts = sorted([wy for wy in range(min_wy, max_wy + 1) if (max_wx, wy) in existing_walls])
    if len(east_pts) >= 2:
        for idx in range(len(east_pts) - 1):
            y1, y2 = east_pts[idx], east_pts[idx + 1]
            if 1 < y2 - y1 <= 32:
                gap_cov = any((max_wx, y) in covered_coords or (max_wx - 1, y) in covered_coords for y in range(y1 + 1, y2))
                if gap_cov:
                    wx0_e = (max_wx - center_x) * updater.H_SCALE
                    for y in range(y1 + 1, y2):
                        if (max_wx, y) not in existing_walls:
                            wz0 = (y - center_z) * updater.H_SCALE
                            wz1 = wz0 + updater.H_SCALE
                            yt_e = 2.40
                            if (max_wx, y) in pitched_roof_coords:
                                cnw, cne, csw, cse = roof_corner_y[(max_wx, y)]
                                yt_e = min(yt_e, max(cnw, cne, csw, cse))
                            add_house_box(wx0_e, wx0_e + wall_thick, 0.0, yt_e, wz0, wz1)

    # Process all original items for house (original intact logic)
    for it in items:
        wx, wy, z, item_id, fl, h, name = it
        if item_id in updater.TRUE_PITCHED_ROOFS:
            continue

        wx0 = (wx - center_x) * updater.H_SCALE
        wx1 = wx0 + updater.H_SCALE
        wz0 = (wy - center_z) * updater.H_SCALE
        wz1 = wz0 + updater.H_SCALE
        yb  = (z * updater.V_SCALE) - y_base_ground
        yt  = yb + max(h, 1) * updater.V_SCALE

        is_stair = ("stair" in name) or (item_id in (1850, 1852))
        is_floor = (fl & 0x200 != 0) or ("board" in name) or ("floor" in name) or (item_id in updater.STONE_ROOF_TERRACE) or (item_id in (1981, 1986, 1989)) or (item_id in range(2778, 2787))
        is_window = (item_id in (14, 15, 59, 60)) or ("window" in name)
        is_gable = (item_id in (24, 25, 66, 67, 82, 83)) and ("wall" in name) and (h <= 5)
        is_banister = ("banister" in name) or (item_id in (2236, 2240))
        is_wall = (fl & 0x10 != 0) or ("wall" in name) or (item_id in updater._S_WALLS) or (item_id in updater._E_WALLS) or (item_id in updater._CORN_WALLS)

        if is_floor:
            f_thick = 0.10
            add_house_box(wx0, wx1, yb - f_thick, yb, wz0, wz1)
            continue

        if is_gable:
            add_house_box(wx0, wx1, yb, yt, wz0, wz0 + wall_thick)
            continue

        if is_window:
            is_south = item_id in (14, 59) or item_id in updater._S_WALLS or "south" in name
            y_sill = yb + max(h, 1) * 0.35 * updater.V_SCALE
            y_lintel = yb + max(h, 1) * 0.75 * updater.V_SCALE
            if is_south:
                add_house_box(wx0, wx1, yb, y_sill, wz0, wz0 + wall_thick)
                add_house_box(wx0, wx1, y_lintel, yt, wz0, wz0 + wall_thick)
                add_house_box(wx0, wx0 + 0.25, y_sill, y_lintel, wz0, wz0 + wall_thick)
                add_house_box(wx1 - 0.25, wx1, y_sill, y_lintel, wz0, wz0 + wall_thick)
            else:
                add_house_box(wx0, wx0 + wall_thick, yb, y_sill, wz0, wz1)
                add_house_box(wx0, wx0 + wall_thick, y_lintel, yt, wz0, wz1)
                add_house_box(wx0, wx0 + wall_thick, y_sill, y_lintel, wz0, wz0 + 0.25)
                add_house_box(wx0, wx0 + wall_thick, y_sill, y_lintel, wz1 - 0.25, wz1)
            continue

        if is_banister:
            b_thick = 0.10 * updater.H_SCALE
            add_house_box(wx0, wx1, yb, yt, wz0, wz0 + b_thick)
            continue

        if is_wall:
            is_south  = (item_id in updater._S_WALLS) or ("south" in name)
            is_east   = (item_id in updater._E_WALLS) or ("east" in name)
            is_corner = (item_id in updater._CORN_WALLS) or ("corner" in name)
            is_post   = (item_id in updater._POST_WALLS) or ("post" in name)

            if (wx, wy) in pitched_roof_coords:
                cnw, cne, csw, cse = roof_corner_y[(wx, wy)]
                yt = min(yt, max(cnw, cne, csw, cse))

            if is_south and not is_east:
                add_house_box(wx0, wx1, yb, yt, wz0, wz0 + wall_thick)
            elif is_east and not is_south:
                add_house_box(wx0, wx0 + wall_thick, yb, yt, wz0, wz1)
            elif is_corner:
                add_house_box(wx0, wx0 + wall_thick, yb, yt, wz0, wz1)
                add_house_box(wx0 + wall_thick, wx1, yb, yt, wz0, wz0 + wall_thick)
            elif is_post:
                add_house_box(wx0, wx0 + wall_thick, yb, yt, wz0, wz0 + wall_thick)
            else:
                add_house_box(wx0, wx1, yb, yt, wz0, wz0 + wall_thick)

    # Create the single solid Building_Base object
    mesh_house = bpy.data.meshes.new("Building_Base")
    mesh_house.from_pydata(h_verts, [], h_faces)
    mesh_house.update()
    obj_house = bpy.data.objects.new("Building_Base", mesh_house)
    obj_house.data.materials.append(mat_wall)
    col_house.objects.link(obj_house)
    print(f"[+] Created original Building_Base mesh: {len(h_verts)} vertices, {len(h_faces)} polygons")

    # 2. BUILD ROOF TILES (LEGO: EACH SQUARE IS AN INDEPENDENT BLOCK!)
    step = 3.0 * updater.V_SCALE
    thick = 0.12 * updater.V_SCALE
    roof_block_count = 0

    # Combined roof geometry for standalone model_base_roof.glb / model_base.glb
    r_all_verts = []
    r_all_faces = []

    for it in items:
        wx, wy, z, item_id, fl, h, name = it
        if item_id not in updater.TRUE_PITCHED_ROOFS:
            continue

        wx0 = (wx - center_x) * updater.H_SCALE
        wx1 = wx0 + updater.H_SCALE
        wz0 = (wy - center_z) * updater.H_SCALE
        wz1 = wz0 + updater.H_SCALE
        yb  = (z * updater.V_SCALE) - y_base_ground

        v, f = [], []
        # In Blender: X=wx, Y=wz, Z=yb
        if item_id in updater.ROOF_SLOPE_SOUTH:
            v = [
                (wx0, wz0, yb), (wx1, wz0, yb), (wx1, wz1, yb + step), (wx0, wz1, yb + step),
                (wx0, wz0, yb - thick), (wx1, wz0, yb - thick), (wx1, wz1, yb + step - thick), (wx0, wz1, yb + step - thick)
            ]
            f = [
                (0, 1, 2, 3), # Top slope
                (7, 6, 5, 4), # Underside slope (smooth!)
                (0, 4, 5, 1), # North edge
                (3, 2, 6, 7), # South edge
                (0, 3, 7, 4), # West edge
                (1, 5, 6, 2)  # East edge
            ]
        elif item_id in updater.ROOF_SLOPE_NORTH:
            v = [
                (wx0, wz1, yb), (wx1, wz1, yb), (wx1, wz0, yb + step), (wx0, wz0, yb + step),
                (wx0, wz1, yb - thick), (wx1, wz1, yb - thick), (wx1, wz0, yb + step - thick), (wx0, wz0, yb + step - thick)
            ]
            f = [
                (0, 1, 2, 3),
                (7, 6, 5, 4),
                (0, 4, 5, 1),
                (3, 2, 6, 7),
                (0, 3, 7, 4),
                (1, 5, 6, 2)
            ]
        elif item_id in updater.ROOF_RIDGE_EW:
            wz_mid = wz0 + 0.5 * updater.H_SCALE
            v = [
                (wx0, wz0, yb), (wx1, wz0, yb), (wx1, wz_mid, yb + step), (wx0, wz_mid, yb + step),
                (wx1, wz1, yb), (wx0, wz1, yb),
                (wx0, wz0, yb - thick), (wx1, wz0, yb - thick), (wx1, wz_mid, yb + step - thick), (wx0, wz_mid, yb + step - thick),
                (wx1, wz1, yb - thick), (wx0, wz1, yb - thick)
            ]
            f = [
                (0, 1, 2, 3), (3, 2, 4, 5), # Top slopes
                (9, 8, 7, 6), (11, 10, 8, 9), # Under slopes
                (0, 6, 7, 1), (4, 10, 11, 5)  # Ends
            ]

        if v:
            # 1. Individual LEGO object in Blender collection
            tile_name = f"LEGO_Roof_{wx}_{wy}_z{z}"
            m_tile = bpy.data.meshes.new(tile_name)
            m_tile.from_pydata(v, [], f)
            m_tile.update()
            obj_tile = bpy.data.objects.new(tile_name, m_tile)
            obj_tile.data.materials.append(mat_roof)
            col_roof.objects.link(obj_tile)
            roof_block_count += 1

            # 2. Accumulate in consolidated roof mesh
            base_v = len(r_all_verts)
            r_all_verts.extend(v)
            r_all_faces.extend([[idx + base_v for idx in face] for face in f])

    print(f"[+] Created {roof_block_count} independent LEGO roof tiles in '02_Telhado_Lego'")

    # Save Native Blender File (.blend)
    blend_path = str(bpath / "building_lego.blend")
    bpy.ops.wm.save_as_mainfile(filepath=blend_path)
    print(f"[+] Saved Blender file: {blend_path}")

    # Export Modular GLB (House + 273 roof blocks as individual nodes)
    glb_modular = str(bpath / "model_modular_lego.glb")
    bpy.ops.export_scene.gltf(filepath=glb_modular, export_format='GLB')
    print(f"[+] Saved Modular GLB: {glb_modular}")

    # 3. EXPORT MODEL_BASE.GLB (2 Objects: Building_Base and Building_Roof)
    # Remove individual roof tiles from scene, add single consolidated Building_Roof
    for obj in list(col_roof.objects):
        bpy.data.objects.remove(obj, do_unlink=True)

    m_roof_consolidated = bpy.data.meshes.new("Building_Roof")
    m_roof_consolidated.from_pydata(r_all_verts, [], r_all_faces)
    m_roof_consolidated.update()
    obj_roof_cons = bpy.data.objects.new("Building_Roof", m_roof_consolidated)
    obj_roof_cons.data.materials.append(mat_roof)
    col_roof.objects.link(obj_roof_cons)

    glb_base = str(bpath / "model_base.glb")
    bpy.ops.export_scene.gltf(filepath=glb_base, export_format='GLB')
    print(f"[+] Saved Consolidated GLB (Building_Base + Building_Roof): {glb_base}")

    # Also export standalone house and roof GLBs
    # Standalone house
    obj_roof_cons.hide_set(True)
    obj_house.hide_set(False)
    glb_house = str(bpath / "model_base_house.glb")
    # Export only visible/active
    bpy.ops.export_scene.gltf(filepath=glb_house, export_format='GLB', use_visible=True)
    print(f"[+] Saved Standalone House: {glb_house}")

    # Standalone roof
    obj_roof_cons.hide_set(False)
    obj_house.hide_set(True)
    glb_roof = str(bpath / "model_base_roof.glb")
    bpy.ops.export_scene.gltf(filepath=glb_roof, export_format='GLB', use_visible=True)
    print(f"[+] Saved Standalone Roof: {glb_roof}")

    # Synchronize to community_assets
    target_dir = Path("/home/mnunes/uo3d_map/community_assets/map0_felucca/britain/building_13_royal_guard_outpost")
    if target_dir.exists():
        for fname in ["building_lego.blend", "model_modular_lego.glb", "model_base.glb", "model_base_house.glb", "model_base_roof.glb"]:
            src = bpath / fname
            dst = target_dir / fname
            if src.exists():
                shutil.copy2(src, dst)
        print(f"[+] Synchronized all files to {target_dir}")

if __name__ == "__main__":
    rebuild()
